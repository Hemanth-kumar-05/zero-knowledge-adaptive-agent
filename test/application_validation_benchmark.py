def turn(turn_id, question, metric_tags, objective, **expected_behaviors):
    return {
        "turn_id": turn_id,
        "question": question,
        "metric_tags": metric_tags,
        "objective": objective,
        "expected_behaviors": expected_behaviors,
    }


def session(session_id, session_goal, turns):
    return {
        "session_id": session_id,
        "session_goal": session_goal,
        "turns": turns,
    }


